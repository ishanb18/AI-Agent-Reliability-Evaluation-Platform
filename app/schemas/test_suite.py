"""
TestSuite + TestCase Pydantic Schemas — request/response shapes for /test-suites endpoints.

Handles:
  - Test suite CRUD validation
  - Individual test case creation
  - Bulk upload result reporting (how many created, how many failed)
  - Seed generation trigger response
"""

import datetime
from typing import Optional, List
from pydantic import BaseModel, Field
from enum import Enum


class TestCaseCategory(str, Enum):
    """Categories of evaluation a test case targets."""
    general = "general"           # Basic QA / factual correctness
    rag = "rag"                   # RAG retrieval / faithfulness
    tool_use = "tool_use"         # Tool selection and argument accuracy
    instruction = "instruction"   # System prompt / instruction following
    security = "security"         # Prompt injection / jailbreak / PII


class RiskLevel(str, Enum):
    """How critical a test case failure would be."""
    low = "low"
    medium = "medium"
    high = "high"
    critical = "critical"


class TestCaseSource(str, Enum):
    """Where the test case came from."""
    user = "user"           # Manually created by the user
    generated = "generated" # Auto-generated by our platform's LLM
    security = "security"   # Security-focused auto-generated
    seed = "seed"           # Pre-built seed dataset


class TestCaseStatus(str, Enum):
    """Review status for auto-generated test cases (Day 5)."""
    active = "active"                   # Normal — included in evaluation runs
    pending_review = "pending_review"   # Auto-generated — awaiting user approval
    rejected = "rejected"               # User rejected after review


# ── Test Case Schemas ─────────────────────────────────────────────────────────

class TestCaseCreate(BaseModel):
    """Request body for adding a single test case to a suite."""
    input: str = Field(
        ...,
        min_length=1,
        description="The test prompt/question sent to the agent",
        examples=["Can I cancel my order #12345?"],
    )
    expected_answer: Optional[str] = Field(
        default=None,
        description="Ground truth correct answer for comparison",
        examples=["Yes, I can help you cancel order #12345."],
    )
    expected_tools: Optional[List[str]] = Field(
        default=None,
        description="Tools the agent SHOULD call for this test",
        examples=[["get_order", "cancel_order"]],
    )
    category: TestCaseCategory = Field(
        default=TestCaseCategory.general,
        description="What aspect this test evaluates",
    )
    risk_level: RiskLevel = Field(
        default=RiskLevel.low,
        description="How critical a failure on this test would be",
    )
    source: TestCaseSource = Field(
        default=TestCaseSource.user,
        description="Origin of this test case",
    )
    status: TestCaseStatus = Field(
        default=TestCaseStatus.active,
        description="Review status: active (in eval runs), pending_review (awaiting approval), rejected",
    )


class TestCaseResponse(BaseModel):
    """Response shape for a single test case."""
    id: int
    suite_id: int
    input: str
    expected_answer: Optional[str] = None
    expected_tools: Optional[List[str]] = None  # deserialized from JSON string
    category: str
    risk_level: str
    source: str
    status: str = "active"
    created_at: Optional[datetime.datetime] = None

    model_config = {"from_attributes": True}


# ── Test Suite Schemas ────────────────────────────────────────────────────────

class TestSuiteCreate(BaseModel):
    """Request body for POST /test-suites — create a new test suite."""
    name: str = Field(
        ...,
        min_length=1,
        max_length=200,
        description="Name for the test suite",
        examples=["Customer Support Edge Cases"],
    )
    description: Optional[str] = Field(
        default=None,
        description="What this test suite covers",
        examples=["Edge cases for order cancellation, refund, and shipping queries"],
    )
    agent_id: Optional[int] = Field(
        default=None,
        description="Link this suite to a specific agent (null = universal suite)",
    )


class TestSuiteResponse(BaseModel):
    """Response shape for a test suite — includes nested test cases."""
    id: int
    name: str
    description: Optional[str] = None
    agent_id: Optional[int] = None
    test_cases: List[TestCaseResponse] = []
    case_count: int = 0
    created_at: Optional[datetime.datetime] = None

    model_config = {"from_attributes": True}


class TestSuiteListResponse(BaseModel):
    """Lightweight response for listing suites (without full case details)."""
    id: int
    name: str
    description: Optional[str] = None
    agent_id: Optional[int] = None
    case_count: int = 0
    created_at: Optional[datetime.datetime] = None

    model_config = {"from_attributes": True}


# ── Bulk Upload Schemas ───────────────────────────────────────────────────────

class UploadError(BaseModel):
    """Details about a single failed row during bulk upload."""
    row: int = Field(description="Row number (1-indexed) that failed validation")
    error: str = Field(description="What went wrong with this row")


class BulkUploadResponse(BaseModel):
    """Response for POST /test-suites/{id}/upload — summarizes upload results."""
    suite_id: int
    created: int = Field(description="Number of test cases successfully created")
    errors: int = Field(description="Number of rows that failed validation")
    error_details: List[UploadError] = Field(
        default_factory=list,
        description="Details about each failed row",
    )


class SeedResponse(BaseModel):
    """Response for POST /test-suites/seed — confirms seed population."""
    suite_id: int
    suite_name: str
    cases_created: int
    categories: dict = Field(
        description="Breakdown of created cases by category",
        examples=[{"general": 8, "rag": 7, "tool_use": 7, "instruction": 6, "security": 7}],
    )
